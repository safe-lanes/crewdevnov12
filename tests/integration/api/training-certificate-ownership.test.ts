import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { randomUUID } from "node:crypto";
import { Pool } from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import express from "express";
import request from "supertest";

vi.mock("@server/v2/db", () => ({ getDb: vi.fn() }));
// Only the unrelated suggestions side effect is stubbed. Controller, service,
// crew validation and repository all run against real isolated PostgreSQL tables.
vi.mock("@server/v2/training-needs/complianceSuggestions", () => ({
  lockCrewSuggestionAssignments: vi.fn(async () => {}),
  reconcileCrewSuggestions: vi.fn(async () => {}),
}));
vi.mock("@server/v2/crew-pool/services", async () => ({
  crewCertificatesService: (await import("@server/v2/crew-pool/services/crewCertificatesService")).crewCertificatesService,
}));
import { getDb } from "@server/v2/db";
import { crewTrainingController } from "@server/v2/crew-pool/controllers/crewTrainingController";
import { crewCertificatesService } from "@server/v2/crew-pool/services/crewCertificatesService";
import { CrewTrainingRepository } from "@server/v2/crew-pool/repositories/crewTrainingRepository";
import { CertificateOwnershipError } from "@server/v2/crew-pool/utils/certificateOwnership";

const schema = `certificate_owner_${randomUUID().replaceAll("-", "")}`;
const owner = randomUUID(), other = randomUUID(), train = randomUUID();
let control: Pool, pool: Pool;
const repository = new CrewTrainingRepository();
const app = express();
app.use(express.json());
app.post("/crew/:crewUuid/training", crewTrainingController.create);
app.patch("/crew/:crewUuid/training/:trainUuid", crewTrainingController.update);

beforeAll(async () => {
  if (!process.env.TEST_DATABASE_URL || process.env.TEST_DATABASE_VERIFIED !== "true")
    throw Error("Registered, identity-verified TEST_DATABASE_URL required.");
  control = new Pool({ connectionString: process.env.TEST_DATABASE_URL });
  await control.query(`CREATE SCHEMA "${schema}"`);
  for (const table of ["crew_members_v2", "crew_training_courses"]) {
    await control.query(`CREATE TABLE "${schema}"."${table}" (LIKE public."${table}" INCLUDING DEFAULTS)`);
    // Preserve normal column defaults, but give each clone its own ID sequence.
    await control.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id DROP DEFAULT`);
    await control.query(`ALTER TABLE "${schema}"."${table}" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH 100)`);
  }
  pool = new Pool({ connectionString: process.env.TEST_DATABASE_URL, options: `-c search_path=${schema}` });
  vi.mocked(getDb).mockReturnValue(drizzle(pool) as any);
  await pool.query(`INSERT INTO crew_members_v2(id,crew_uuid,emp_no,first_name,is_deleted)
    VALUES(1,$1,'TEST-OWNER-A','TEST ONLY Owner',false),(2,$2,'TEST-OWNER-B','TEST ONLY Other',false)`, [owner, other]);
});

beforeEach(async () => {
  await pool.query("DELETE FROM crew_training_courses");
  await pool.query(`INSERT INTO crew_training_courses(id,train_uuid,crew_uuid,course_id,training_course,certificate_no,is_deleted)
    VALUES(1,$1,$2,'TEST-COURSE','TEST ONLY training','ORIGINAL',false)`, [train, owner]);
});

afterAll(async () => {
  await pool?.end();
  if (control) {
    await control.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`);
    await control.end();
  }
});

const path = () => `/crew/${owner}/training/${train}`;
const stored = async () => (await pool.query("SELECT * FROM crew_training_courses WHERE train_uuid=$1", [train])).rows[0];

describe("training certificate ownership is immutable on ordinary update", () => {
  it.each([other, null, ""])("PATCH rejects owner %s and preserves the entire row", async crewUuid => {
    const before = await stored();
    const res = await request(app).patch(path()).send({ crewUuid, certificateNo: "MUST NOT SAVE" });
    expect(res.status).toBe(409);
    expect(res.body.error).toBe("certificate_ownership_immutable");
    expect(res.body.message).toBe("Certificate ownership cannot be changed. Delete the certificate and re-create it against the correct seafarer.");
    expect(await stored()).toEqual(before);
  });

  it("ordinary PATCH still edits certificate fields without changing its owner", async () => {
    const res = await request(app).patch(path()).send({ certificateNo: "RENEWED", expiry: "2030-10-31" });
    expect(res.status).toBe(200);
    expect(await stored()).toMatchObject({ crew_uuid: owner, certificate_no: "RENEWED", expiry: "2030-10-31" });
  });

  it("repeating the same owner is accepted but does not transfer ownership", async () => {
    const res = await request(app).patch(path()).send({ crewUuid: owner, certificateNo: "SAME OWNER" });
    expect(res.status).toBe(200);
    expect(await stored()).toMatchObject({ crew_uuid: owner, certificate_no: "SAME OWNER" });
  });

  it("creation still sets the owner from the crew UUID normally", async () => {
    const res = await request(app).post(`/crew/${other}/training`)
      .send({ courseId: "TEST-COURSE", trainingCourse: "TEST ONLY created", certificateNo: "NEW" });
    expect(res.status).toBe(201);
    expect(res.body.crewUuid).toBe(other);
    expect((await pool.query("SELECT crew_uuid FROM crew_training_courses WHERE train_uuid=$1",
      [res.body.trainUuid])).rows[0].crew_uuid).toBe(other);
  });

  it("direct service updates cannot bypass the ownership check", async () => {
    const before = await stored();
    await expect(crewCertificatesService.updateTraining(train, { crewUuid: other, certificateNo: "BAD" }))
      .rejects.toBeInstanceOf(CertificateOwnershipError);
    expect(await stored()).toEqual(before);
  });

  it("repository updates cannot bypass it, but still accept normal fields", async () => {
    const before = await stored();
    await expect(repository.update(train, { crewUuid: other, certificateNo: "BAD" }))
      .rejects.toBeInstanceOf(CertificateOwnershipError);
    expect(await stored()).toEqual(before);
    expect(await repository.update(train, { crewUuid: owner, certificateNo: "OK" }))
      .toMatchObject({ crewUuid: owner, certificateNo: "OK" });
  });

  it("reconciliation rejects an injected owner and rolls back earlier edits", async () => {
    const before = await stored();
    await expect(crewCertificatesService.reconcileTrainingWithAttachments(owner, [
      { trainUuid: train, data: { certificateNo: "FIRST" } },
      { trainUuid: train, data: { crewUuid: other, certificateNo: "BAD" } as any },
    ])).rejects.toBeInstanceOf(CertificateOwnershipError);
    expect(await stored()).toEqual(before);
  });

  it("course identifiers remain ordinarily editable; this change protects only crewUuid", async () => {
    const res = await request(app).patch(path()).send({ courseId: "TEST-OTHER-COURSE" });
    expect(res.status).toBe(200);
    expect(await stored()).toMatchObject({ crew_uuid: owner, course_id: "TEST-OTHER-COURSE" });
  });
});
