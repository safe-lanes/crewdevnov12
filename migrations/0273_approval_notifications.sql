-- 0273: In-app approval notifications, one row per person (Crewing host layer, not the engine).
-- Written by server/v2/approvals/notifier.ts for the same events and the same people as the
-- approval emails: approval needed (approvers of the active step), approved / returned
-- (submitter), withdrawn (approvers who were waiting). Read state is per person.
-- Office-only like the engine tables; never synced to vessels.
-- Idempotent: IF NOT EXISTS everywhere, no hardcoded ids, no CHECK constraints on text.

CREATE TABLE IF NOT EXISTS approval_notifications_v2 (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  anuuid TEXT NOT NULL UNIQUE,
  user_uuid TEXT NOT NULL,
  kind TEXT NOT NULL,                 -- 'pending' | 'approved' | 'returned' | 'withdrawn'
  requuid TEXT NOT NULL,
  node_key TEXT NOT NULL DEFAULT '',  -- the step, for 'pending' (a request notifies once per step)
  module_id TEXT NOT NULL,
  screen_id TEXT NOT NULL,
  action_id TEXT NOT NULL DEFAULT '',
  subject_ref TEXT NOT NULL,
  title TEXT NOT NULL,
  message TEXT NOT NULL DEFAULT '',
  link TEXT,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The same event never notifies the same person twice.
CREATE UNIQUE INDEX IF NOT EXISTS uniq_approval_notifications_v2_event
  ON approval_notifications_v2 (requuid, user_uuid, kind, node_key);
CREATE INDEX IF NOT EXISTS idx_approval_notifications_v2_user
  ON approval_notifications_v2 (user_uuid, is_read, created_at DESC);
